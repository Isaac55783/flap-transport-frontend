
import React, { useEffect, useState } from 'react';

import {
  StyleSheet,
  KeyboardAvoidingView,
  Platform,
  ScrollView,
} from 'react-native';

import {
  TextInput,
  Button,
  Text,
  Surface,
  HelperText,
  useTheme,
} from 'react-native-paper';

import { apiService } from '../services/api';
import { socketService } from '../services/socket';
import { useAppDispatch } from '../store';

import {
  authSuccess,
  startAuth,
  authFailure,
} from '../store/authSlice';

export default function OTPScreen({ route, navigation }: any) {
  const theme = useTheme();
  const dispatch = useAppDispatch();

  // Read details passed from registration or login.
  const phoneNumber = route?.params?.phoneNumber;

  // The backend uses "passenger", not "customer".
  const incomingRole = route?.params?.role || 'passenger';
  const role =
    incomingRole === 'customer' ? 'passenger' : incomingRole;

  const registeredFullName =
    typeof route?.params?.fullName === 'string'
      ? route.params.fullName.trim()
      : '';

  const email =
    typeof route?.params?.email === 'string'
      ? route.params.email.trim()
      : '';

  const dob =
    typeof route?.params?.dob === 'string'
      ? route.params.dob.trim()
      : '';

  const emergencyContact =
    typeof route?.params?.emergencyContact === 'string'
      ? route.params.emergencyContact.trim()
      : '';

  // Use the OTP already generated by the previous screen.
  const passedOtp =
    route?.params?.mockCode ??
    route?.params?.otp ??
    '';

  const [otpCode, setOtpCode] = useState('');
  const [webTestingOtp, setWebTestingOtp] = useState(
    /^\d{6}$/.test(String(passedOtp))
      ? String(passedOtp)
      : ''
  );
  const [isLoading, setIsLoading] = useState(false);
  const [errorMsg, setErrorMsg] = useState<string | null>(null);

  // Update the displayed testing code if navigation supplies a new code.
  useEffect(() => {
    const code = String(
      route?.params?.mockCode ??
      route?.params?.otp ??
      ''
    );

    setWebTestingOtp(/^\d{6}$/.test(code) ? code : '');
    setOtpCode('');
    setErrorMsg(null);
  }, [
    route?.params?.mockCode,
    route?.params?.otp,
  ]);

  const handleVerifyOTP = async () => {
    if (isLoading) return;

    setErrorMsg(null);

    const trimmedOtp = otpCode.trim();

    if (!phoneNumber) {
      setErrorMsg(
        'Phone number is missing. Please return to the login screen.'
      );
      return;
    }

    if (!trimmedOtp) {
      setErrorMsg('Please enter the 6-digit verification code.');
      return;
    }

    if (!/^\d{6}$/.test(trimmedOtp)) {
      setErrorMsg('The verification code must contain exactly 6 digits.');
      return;
    }

    setIsLoading(true);
    dispatch(startAuth());

    try {
      // Verify the code with the Flask backend.
      const res = await apiService.verify(
        phoneNumber,
        trimmedOtp,
        role
      );

      if (!res?.access_token) {
        throw new Error(
          'The server did not return an access token. Please try again.'
        );
      }

      if (!res?.user) {
        throw new Error(
          'The server verified the code but did not return user information.'
        );
      }

      // Use the registration name when available.
      // Otherwise, use the name stored on the backend account.
      const backendName =
        res.user.name ||
        res.user.full_name ||
        res.user.fullName ||
        [
          res.user.first_name,
          res.user.last_name,
        ]
          .filter(Boolean)
          .join(' ')
          .trim();

      const finalName =
        registeredFullName ||
        (typeof backendName === 'string' ? backendName.trim() : '');

      const authenticatedUser = {
        ...res.user,

        // Do not replace a valid backend name with an empty value.
        ...(finalName ? { name: finalName } : {}),

        // Preserve optional passenger registration details.
        ...(role === 'passenger'
          ? {
              ...(email ? { email } : {}),
              ...(dob ? { dob } : {}),
              ...(emergencyContact
                ? { emergencyContact }
                : {}),
            }
          : {}),
      };

      // Save the authenticated session.
      dispatch(
        authSuccess({
          token: res.access_token,
          user: authenticatedUser,
          profile: res.profile,
        })
      );

      // A socket error must not cancel successful OTP verification.
      try {
        socketService.connect();
      } catch (socketError) {
        console.warn(
          'Socket connection failed:',
          socketError
        );
      }

      // Navigate according to the verified account role.
      const authenticatedRole =
        res.role ||
        authenticatedUser.role ||
        role;

      if (authenticatedRole === 'admin') {
        navigation.replace('AdminDashboard');
      } else if (authenticatedRole === 'driver') {
        navigation.replace('DriverDashboard');
      } else {
        navigation.replace('PassengerDashboard');
      }
    } catch (err: any) {
      console.error('OTP verification failed:', err);

      const message =
        err?.response?.data?.error ||
        err?.response?.data?.message ||
        err?.message ||
        'Verification failed. Please check your code and try again.';

      setErrorMsg(message);
      dispatch(authFailure(message));
    } finally {
      setIsLoading(false);
    }
  };

  return (
    <KeyboardAvoidingView
      behavior={Platform.OS === 'ios' ? 'padding' : 'height'}
      style={[
        styles.container,
        { backgroundColor: theme.colors.background },
      ]}
    >
      <ScrollView
        contentContainerStyle={styles.scroll}
        keyboardShouldPersistTaps="handled"
      >
        <Surface style={styles.card} elevation={2}>
          <Text variant="titleLarge" style={styles.title}>
            Enter OTP Code
          </Text>

          <Text variant="bodyMedium" style={styles.subtitle}>
            Enter the 6-digit verification code for {phoneNumber}.
          </Text>

          {Platform.OS === 'web' && (
            <Surface style={styles.webOtpBox} elevation={0}>
              <Text
                variant="labelMedium"
                style={styles.webOtpLabel}
              >
                TEMPORARY WEB TESTING CODE
              </Text>

              <Text
                variant="headlineMedium"
                style={styles.webOtpCode}
              >
                {webTestingOtp || 'Not supplied'}
              </Text>

              <Text
                variant="bodySmall"
                style={styles.webOtpNote}
              >
                This displays the code passed from the previous
                screen. It does not generate a new code.
              </Text>
            </Surface>
          )}

          <TextInput
            label="6-Digit Verification Code"
            value={otpCode}
            onChangeText={(text) => {
              setOtpCode(
                text.replace(/[^0-9]/g, '').slice(0, 6)
              );

              if (errorMsg) {
                setErrorMsg(null);
              }
            }}
            keyboardType="number-pad"
            maxLength={6}
            mode="outlined"
            placeholder="123456"
            left={<TextInput.Icon icon="key" />}
            style={styles.input}
            disabled={isLoading}
            error={!!errorMsg}
            autoFocus
          />

          {errorMsg && (
            <HelperText type="error" visible>
              {errorMsg}
            </HelperText>
          )}

          <Button
            mode="contained"
            onPress={handleVerifyOTP}
            loading={isLoading}
            disabled={isLoading}
            style={styles.button}
            contentStyle={styles.btnContent}
          >
            Confirm &amp; Log In
          </Button>

          <Button
            mode="text"
            onPress={() => navigation.goBack()}
            style={styles.backButton}
            disabled={isLoading}
          >
            Back to Login
          </Button>
        </Surface>
      </ScrollView>
    </KeyboardAvoidingView>
  );
}

const styles = StyleSheet.create({
  container: {
    flex: 1,
  },
  scroll: {
    flexGrow: 1,
    justifyContent: 'center',
    padding: 20,
  },
  card: {
    padding: 24,
    borderRadius: 20,
    width: '100%',
    maxWidth: 400,
    alignSelf: 'center',
  },
  title: {
    fontWeight: 'bold',
    color: '#00A859',
    marginBottom: 8,
    textAlign: 'center',
  },
  subtitle: {
    color: '#666',
    textAlign: 'center',
    marginBottom: 24,
    lineHeight: 20,
  },
  webOtpBox: {
    padding: 16,
    marginBottom: 20,
    borderRadius: 12,
    alignItems: 'center',
    backgroundColor: '#E8F5E9',
  },
  webOtpLabel: {
    color: '#1B5E20',
    textAlign: 'center',
    fontWeight: 'bold',
  },
  webOtpCode: {
    color: '#087F43',
    fontWeight: 'bold',
    letterSpacing: 6,
    marginVertical: 8,
  },
  webOtpNote: {
    color: '#1B5E20',
    textAlign: 'center',
  },
  input: {
    marginBottom: 6,
    textAlign: 'center',
    letterSpacing: 8,
    fontSize: 20,
  },
  button: {
    marginTop: 16,
    borderRadius: 12,
  },
  btnContent: {
    paddingVertical: 8,
  },
  backButton: {
    marginTop: 12,
  },
});
